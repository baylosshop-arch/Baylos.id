const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(new URL('../web/baylos-validation.js', `file://${__filename}`), 'utf8');
const context = { window: {}, URL };
vm.runInNewContext(source, context);
const v = context.window.BaylosValidation;
assert.equal(v.required(' Baylos ', 'Nama'), 'Baylos');
assert.throws(() => v.required('  ', 'Nama'), /wajib diisi/);
assert.equal(v.email(' TEST@EXAMPLE.COM '), 'test@example.com');
assert.throws(() => v.email('bukan-email'), /email/);
assert.equal(v.phone('+62 812-3456-7890'), '+62 812-3456-7890');
assert.throws(() => v.phone('123'), /telepon/);
assert.equal(v.quantity('3'), 3);
assert.throws(() => v.quantity(0), /Jumlah/);
assert.equal(v.rupiah('12000'), 12000);
assert.throws(() => v.rupiah(-1), /Nominal/);
assert.equal(v.httpsUrl('https://example.com/image.png'), 'https://example.com/image.png');
assert.throws(() => v.httpsUrl('http://example.com'), /HTTPS/);
assert.equal(v.postalCode('55281'), '55281');
assert.throws(() => v.postalCode('!!'), /pos/);
assert.equal(v.escapeHtml('<script>'), '&lt;script&gt;');
console.log('PASS: 16 assertion validasi Baylos.');
